import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {Controller} from '../plugins/autonomy-team/runtime/engine.mjs';
import {listAgents,previewAgent,manageAgent,recoverAgentManagement} from '../plugins/autonomy-team/runtime/agent-management.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'sodam-management-'));
try {
 const c=new Controller(root);c.initialize({authorize:true,autoPilot:true});
 assert.equal(listAgents(c).items.filter(x=>x.type==='project-generated').length,0);
 assert.equal(listAgents(c).items.filter(x=>x.type==='provided-workflow').length,14);
 for(const id of ['one','two'])c.record({id,taskId:id,kind:'docs',gap:'review',outcome:'failed',cause:'missing-role',seconds:1,corrections:0,evidence:[]});
 const name=c.cycle({kind:'docs',gap:'review'}).activated;
 assert.equal(listAgents(c,{name}).items.length,1);
 const original=fs.readFileSync(c.safe(c.state().agents[0].relativePath));
 const act=action=>{const p=previewAgent(c,{name,action});return manageAgent(c,{name,action,snapshot:p.snapshot,authorize:true,externalImpactAcknowledged:true});};
 const stale=previewAgent(c,{name,action:'disable'});
 assert.throws(()=>manageAgent(c,{...stale,authorize:true}));
 act('protect');assert.equal(previewAgent(c,{name,action:'disable'}).allowed,false);
 assert.throws(()=>manageAgent(c,{name,action:'disable',snapshot:stale.snapshot,authorize:true,externalImpactAcknowledged:true}));
 act('unprotect');
 const p=previewAgent(c,{name,action:'disable'});
 assert.throws(()=>manageAgent(c,{name,action:'disable',snapshot:p.snapshot,authorize:true}));
 act('disable');assert.equal(c.plan({taskId:'later',kind:'docs',gap:'review',goal:'check'}).generatedAgent,null);
 assert.equal(c.cycle({kind:'docs',gap:'review'}).unchanged,true);
 assert.throws(()=>c.propose({kind:'docs',gap:'review'}));
 act('archive');assert.equal(c.state().agents[0].status,'archived');
 act('restore');assert.equal(c.state().agents[0].status,'disabled');
 act('enable');assert.equal(c.state().agents[0].status,'pilot');
 assert.deepEqual(fs.readFileSync(c.safe(c.state().agents[0].relativePath)),original);
 assert.equal(c.state().experiences.length,2);
 const before=JSON.stringify(c.state()),write=c.write.bind(c);
 c.write=(file,...args)=>{if(file.includes('management-backups'))throw Object.assign(new Error('test'),{code:'ENOSPC'});return write(file,...args);};
 assert.throws(()=>act('disable'));assert.equal(JSON.stringify(c.state()),before);c.write=write;
 c.write=(file,...args)=>{if(file.endsWith('agent-management.json'))throw Object.assign(new Error('test'),{code:'ENOSPC'});return write(file,...args);};
 assert.throws(()=>act('disable'));c.write=write;
 assert.throws(()=>listAgents(c));assert.throws(()=>c.transaction(()=>{}));
 const pending=c.read('.sodam-agent/agent-management-pending.json');
 assert.throws(()=>recoverAgentManagement(c,{authorize:true,backupSha256:'0'.repeat(64)}));
 assert.equal(recoverAgentManagement(c,{authorize:true,backupSha256:pending.sha256}).recovered,true);
 assert.equal(JSON.stringify(c.state()),before);
 let failOnce=true;
 c.write=(file,...args)=>{if(file.endsWith('agent-management.json') && failOnce){failOnce=false;throw Object.assign(new Error('test'),{code:'ENOSPC'});}return write(file,...args);};
 assert.throws(()=>act('disable'));assert.equal(JSON.stringify(c.state()),before);c.write=write;
 c.write('.sodam-agent/hooks.json',{turns:[{status:'open',plan:{agent:name}}]});
 assert.ok(previewAgent(c,{name,action:'disable'}).blocked.includes('in-use'));
 assert.throws(()=>previewAgent(c,{name,action:'delete'}));
 assert.throws(()=>listAgents(c,{query:1}));
 console.log('PASS: agent inventory, preview, protection, consent, stale snapshots, disable/archive/restore/enable, backup failure and history preservation');
} finally {fs.rmSync(root,{recursive:true,force:true});}
